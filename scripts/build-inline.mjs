// Builds dist/inline-worker.js: the normal worker (src/worker.js) plus every file in public/
// embedded in the script, so the site can be deployed WITHOUT Workers static-asset uploads.
//
// Why: in proxied environments that inject an API token into every request to
// api.cloudflare.com, wrangler's asset-upload step fails (its one-time upload JWT is replaced
// by the API token -> 401). Deploying with assets inlined avoids that step entirely.
//
// Usage:  node scripts/build-inline.mjs && npx wrangler deploy -c wrangler.inline.jsonc
// The regular `npx wrangler deploy` (wrangler.jsonc, with static assets) keeps working as before.

import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const PUBLIC = join(ROOT, "public");

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".mjs": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".webmanifest": "application/manifest+json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
};
const TEXT = new Set([".html", ".css", ".js", ".mjs", ".json", ".webmanifest", ".svg", ".txt"]);

// Mirrors public/_headers
function cacheFor(path) {
  if (path === "/app.js" || path === "/styles.css") return "public, max-age=3600, stale-while-revalidate=604800";
  if (/\.(png|svg|jpg|jpeg|webp|ico)$/.test(path)) return "public, max-age=86400, stale-while-revalidate=604800";
  if (path.endsWith(".webmanifest")) return "public, max-age=86400";
  return "no-cache";
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = {};
for (const full of walk(PUBLIC)) {
  const path = "/" + relative(PUBLIC, full).split("\\").join("/");
  if (path === "/_headers" || path === "/_redirects") continue;
  const ext = extname(full).toLowerCase();
  const type = TYPES[ext] || "application/octet-stream";
  const buf = readFileSync(full);
  files[path] = TEXT.has(ext)
    ? { type, cache: cacheFor(path), text: buf.toString("utf8") }
    : { type, cache: cacheFor(path), b64: buf.toString("base64") };
}

const out = `// GENERATED by scripts/build-inline.mjs — do not edit. Source: src/worker.js + public/
import app from "../src/worker.js";

const FILES = ${JSON.stringify(files)};

function decode(b64) {
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}

// Stand-in for the static-assets binding, with single-page-app fallback to /index.html
const ASSETS = {
  async fetch(request) {
    const url = new URL(request.url);
    let path = decodeURIComponent(url.pathname);
    if (path.endsWith("/")) path += "index.html";
    let file = FILES[path];
    if (!file) file = FILES["/index.html"];
    const body = file.text !== undefined ? file.text : decode(file.b64);
    const headers = { "content-type": file.type, "cache-control": file === FILES["/index.html"] ? "no-cache" : file.cache };
    return new Response(request.method === "HEAD" ? null : body, { headers });
  },
};

export default {
  fetch(request, env, ctx) {
    return app.fetch(request, { ...env, ASSETS }, ctx);
  },
};
`;
mkdirSync(join(ROOT, "dist"), { recursive: true });
writeFileSync(join(ROOT, "dist", "inline-worker.js"), out);
const kb = (Buffer.byteLength(out) / 1024).toFixed(0);
console.log(`dist/inline-worker.js written: ${Object.keys(files).length} files inlined, ${kb} KB`);
